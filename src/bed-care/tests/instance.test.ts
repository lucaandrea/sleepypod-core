import { beforeEach, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ monitor: vi.fn(), status: vi.fn(), at: vi.fn(), block: vi.fn(), recording: vi.fn(), backup: vi.fn() }))
vi.mock('@/src/hardware/dacMonitor.instance', () => ({ getDacMonitorIfRunning: mocks.monitor }))
vi.mock('@/src/hardware/pumpStallGuard', () => ({ shouldBlock: mocks.block }))
vi.mock('@/src/recording-health/instance', () => ({ getRecordingHealth: mocks.recording }))
vi.mock('@/src/lib/dbInspect', () => ({ lastBackupAt: mocks.backup }))
const { getBedCare } = await import('../instance')
beforeEach(() => {
  vi.resetAllMocks()
  mocks.monitor.mockReturnValue({ getFreshStatus: mocks.status, getLastPollAt: mocks.at })
  mocks.status.mockReturnValue({ waterLevel: 'ok', isPriming: false })
  mocks.at.mockImplementation(Date.now)
  mocks.block.mockReturnValue(false)
  mocks.backup.mockResolvedValue(Date.now() - 1000)
  mocks.recording.mockResolvedValue(null)
})
it('reuses the running observation without requesting hardware writes or starting a monitor', async () => {
  const report = await getBedCare()
  expect(mocks.status).toHaveBeenCalledExactlyOnceWith(30_000)
  expect(mocks.block.mock.calls).toEqual([['left'], ['right']])
  expect(report.checks[0].state).toBe('checked')
})
it('keeps independent failures unknown and does not claim inactive protections before a fresh monitor read', async () => {
  mocks.status.mockReturnValue(null)
  mocks.backup.mockRejectedValue(new Error('private path'))
  mocks.recording.mockRejectedValue(new Error('private database'))
  const report = await getBedCare()
  expect(report.checks.every(check => check.state === 'unknown')).toBe(true)
  expect(JSON.stringify(report)).not.toContain('private path')
  mocks.block.mockImplementation(side => side === 'right')
  expect((await getBedCare()).checks.find(check => check.id === 'circulation')?.state).toBe('attention')
})
