import { expect, test } from '@playwright/test'

const DESTINATIONS = ['Tonight', 'Sleep', 'Autopilot', 'Home', 'More']

test('five destinations retain routines, settings, diagnostics and owner sign-out', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'WebGLRenderingContext', { value: undefined })
  })
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  await page.goto('/en/schedule')
  const navigation = page.locator('nav[aria-label="Main"]:visible')
  await expect(navigation.locator('[data-primary-destination]')).toHaveText(DESTINATIONS)
  await expect(navigation.getByRole('link', { name: 'Routines & wake alarms', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(navigation.getByRole('link', { name: 'Tonight', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await page.screenshot({ path: test.info().outputPath('desktop-routines.png'), fullPage: true, animations: 'disabled' })

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(navigation.getByRole('link')).toHaveText(DESTINATIONS)
  await expect(navigation.getByRole('link', { name: 'Tonight', exact: true })).toHaveAttribute('aria-current', 'page')
  for (const name of ['Sleep', 'Autopilot', 'Home', 'More']) {
    await navigation.getByRole('link', { name, exact: true }).click()
    await expect(navigation.getByRole('link', { name, exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('main').locator('h1')).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  }
  await expect(page.getByRole('heading', { name: 'More', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/en\/more$/)
  await page.getByRole('main').getByRole('link', { name: /^Routines & wake alarms/ }).click()
  await expect(page).toHaveURL(/\/en\/schedule$/)
  await navigation.getByRole('link', { name: 'More', exact: true }).click()
  await page.screenshot({ path: test.info().outputPath('phone-more-light.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('main').getByRole('link', { name: /^System health/ }).click()
  await expect(page).toHaveURL(/\/en\/system$/)
  await expect(navigation.getByRole('link', { name: 'More', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.goto('/en/settings?section=appearance')
  await expect(navigation.getByRole('link', { name: 'More', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(navigation.getByRole('link', { name: 'Appearance', exact: true })).toHaveAttribute('aria-current', 'page')
  await navigation.getByRole('link', { name: 'More', exact: true }).click()
  await page.screenshot({ path: test.info().outputPath('desktop-more-light.png'), fullPage: true, animations: 'disabled' })

  await page.setViewportSize({ width: 390, height: 844 })
  await navigation.getByRole('link', { name: 'Tonight', exact: true }).click()
  const stage = page.getByTestId('temp-stage')
  await expect(stage).toBeVisible()
  await expect(page).toHaveTitle('Tonight · Sleepypod')
  await expect(page.getByTestId('stage-fallback').locator(':scope > .text-fg')).toHaveCSS('color', 'rgb(17, 17, 19)')
  await stage.getByRole('link', { name: 'Routines', exact: true }).click()
  await expect(page).toHaveURL(/\/en\/schedule$/)
  await navigation.getByRole('link', { name: 'Tonight', exact: true }).click()
  await expect(stage).toBeVisible()
  await expect(page.getByTestId('stage-fallback')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('phone-tonight-stage.png'), animations: 'disabled' })
  await stage.getByRole('button', { name: 'Cards', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tonight', exact: true })).toBeVisible()
  await expect(page.getByRole('main').getByRole('link', { name: 'Routines', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('phone-tonight-cards.png'), fullPage: true, animations: 'disabled' })

  await navigation.getByRole('link', { name: 'More', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('heading', { name: 'More', exact: true })).toHaveCSS('color', 'rgb(236, 236, 236)')
  await page.screenshot({ path: test.info().outputPath('phone-more-dark.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('main').getByRole('link', { name: /^Browser connection/ }).click()
  await page.getByRole('button', { name: 'Disconnect this browser', exact: true }).click()
  await expect(page.getByLabel('Connection key', { exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Main', exact: true })).toHaveCount(0)
})

test('five destinations remain usable on a narrow phone with enlarged text and a keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 680 })
  await page.goto('/en/more')
  await page.addStyleTag({ content: 'html { font-size: 200%; }' })
  const navigation = page.locator('nav[aria-label="Main"]:visible')
  await expect(page.getByRole('heading', { name: 'Routines & wake alarms', exact: true })).toHaveCSS('font-size', '32px')
  await expect(navigation.getByRole('link')).toHaveText(DESTINATIONS)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  for (const name of DESTINATIONS) {
    const link = navigation.getByRole('link', { name, exact: true })
    const bounds = await link.boundingBox()
    expect(bounds?.width).toBeGreaterThanOrEqual(44)
    expect(bounds?.height).toBeGreaterThanOrEqual(44)
  }
  await navigation.getByRole('link', { name: 'Home', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(navigation.getByRole('link', { name: 'More', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'More', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('phone-large-text-more.png'), fullPage: true, animations: 'disabled' })
  await navigation.getByRole('link', { name: 'Tonight', exact: true }).click()
  await expect(page.getByTestId('temp-stage')).toBeVisible()
  await expect.poll(async () => {
    const stage = await page.getByTestId('temp-stage').boundingBox()
    const bar = await navigation.boundingBox()
    return stage && bar ? Math.abs(stage.y + stage.height - bar.y) : Number.POSITIVE_INFINITY
  }).toBeLessThanOrEqual(1)
})

test('3D bed renders without an internet dependency', async ({ page }) => {
  await page.route(/^https?:\/\/(?!127\.0\.0\.1(?::|\/))/, route => route.abort())
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/en')
  await expect(page.getByTestId('stage-canvas').locator('canvas')).toBeVisible()
  await expect(page.getByTestId('stage-fallback')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('phone-bed-offline.png') })
})
