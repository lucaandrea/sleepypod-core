import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const tokens = JSON.parse(await readFile(new URL('design/unified-tokens.json', root), 'utf8'))
const mapping = {
  'sp-ink-0': 'canvas', 'sp-ink-1': 'surface', 'sp-ink-2': 'border', 'sp-line-1': 'border',
  'sp-line-2': 'border', 'sp-fg-1': 'text', 'sp-fg-2': 'secondary', 'sp-fg-3': 'secondary',
  'sp-fg-icon': 'secondary', 'sp-cool': 'accent', 'accent-link': 'accent',
}
const start = '/* BEGIN UNIFIED DESIGN — generated by scripts/generate-unified-design.mjs */'
const end = '/* END UNIFIED DESIGN */'
const mode = name => Object.entries(mapping).map(([variable, color]) => `  --${variable}: ${tokens.colors[color][name]};`).join('\n')
const generated = `${start}\n:root {\n${mode('dark')}\n  --sp-warm: #ffb46b;\n  --radius-card: ${tokens.layout.cardRadius}px;\n}\n[data-theme="light"] {\n${mode('light')}\n  --sp-warm: #a55418;\n}\n${end}\n`
const file = new URL('app/globals.css', root)
const source = await readFile(file, 'utf8')
const opening = source.indexOf(start)
const closing = source.indexOf(end)
const next = opening < 0 ? `${source.trimEnd()}\n\n${generated}` : source.slice(0, opening) + generated + source.slice(closing + end.length).trimStart()
if (process.argv.includes('--check')) {
  if (source !== next) throw new Error('Unified design output needs regeneration')
}
else await writeFile(file, next)
